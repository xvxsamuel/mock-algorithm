type PixelIconProps = { name: PixelIconName; size?: number };

/** A small icon drawn in square pixels, to match the panel's type. */
function PixelIcon({ name, size = 16 }: PixelIconProps) {
  // One rectangle per run of pixels in a row.
  const runs: { x: number; y: number; w: number }[] = [];
  ART[name].forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x += 1;
        continue;
      }
      let end = x;
      while (end < row.length && row[end] === "#") end += 1;
      runs.push({ x, y, w: end - x });
      x = end;
    }
  });
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 16 16"
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden="true"
    >
      {runs.map(({ x, y, w }) => (
        <rect key={`${x},${y}`} x={x} y={y} width={w} height={1} />
      ))}
    </svg>
  );
}

export default PixelIcon;
